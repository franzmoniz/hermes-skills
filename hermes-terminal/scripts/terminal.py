"""Hermes's Terminal: `hermes` always opens the SAME conversation, called "Hermes's Terminal" and pinned in
the Hermes app, with a short recap of where you stopped.

  python terminal.py open             (the `hermes` wrapper) prints the id of the conversation to resume
                                      (empty = start one) and puts the recap above it
  python terminal.py close <started>  (the `hermes` wrapper, after Hermes closes) names/pins a conversation
                                      started now, writes the recap
  python terminal.py adopt <id> [summary file]   make <id> the terminal conversation (e.g. a conversation
                                      another device sent; used by Hermes Device Sync when installed)
  python terminal.py summarize [id]   write the recap now (needs a recap model, see config)
  python terminal.py current          prints the id of the terminal conversation
  python terminal.py recap [id]       prints the stored recap

The conversation is found by its title: "Hermes's Terminal" and its continuations "Hermes's Terminal #2",
"#3"... (Hermes adds the #N itself when a long conversation is compressed). The one with the newest
message wins, and only that one is pinned. Settings: $HERMES_HOME/hermes-terminal.json
  {"title": "Hermes's Terminal", "summary": {"enabled": true, "provider": "...", "model": "...",
   "language": "English"}}
Works on its own. Other skills can plug in (Hermes Device Sync moves this conversation between devices).
"""
import json, os, re, sqlite3, subprocess, sys, time
from pathlib import Path

sys.dont_write_bytecode = True
QUEUE_PREFIX = "[hermes-sync queued request]"  # unattended requests are never the terminal conversation


def hermes_home():
    h = os.environ.get("HERMES_HOME")
    if h:
        return Path(h)
    if os.name == "nt" and os.environ.get("LOCALAPPDATA"):
        return Path(os.environ["LOCALAPPDATA"]) / "hermes"
    return Path.home() / ".hermes"


HH = hermes_home()
CFG = HH / "hermes-terminal.json"
STATE = HH / "cache" / "hermes-terminal-state.json"
MARK = "# Generated by hermes-terminal (recap of the last conversation). Do not edit."
LEGACY_MARK = "# Generated by hermes-device-sync (recap of the last conversation). Do not edit."


def rj(p, d=None):
    try:
        return json.loads(Path(p).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return d


def wj(p, d):
    p = Path(p)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(d, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def cfg():
    c = {"title": "Hermes's Terminal", "summary": {"enabled": False, "provider": None, "model": None, "language": "English"}}
    u = rj(CFG, {}) or {}
    for k, v in u.items():
        if isinstance(v, dict) and isinstance(c.get(k), dict):
            c[k].update(v)
        else:
            c[k] = v
    return c


def state():
    s = rj(STATE, {}) or {}
    s.setdefault("summaries", {})
    return s


def hermes_bin():
    import shutil
    for c in (HH / "bin" / "hermes.exe", HH / "bin" / "hermes"):
        if c.exists():
            return str(c)
    return shutil.which("hermes") or "hermes"


def hermes(*args):
    r = subprocess.run([hermes_bin(), *args], capture_output=True, text=True, encoding="utf-8", errors="replace",
                       stdin=subprocess.DEVNULL, timeout=120)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def db():
    return sqlite3.connect("file:" + str(HH / "state.db") + "?mode=ro", uri=True, timeout=10)


def last_ts(c, sid):
    r = c.execute("SELECT MAX(timestamp) FROM messages WHERE session_id=?", (sid,)).fetchone()
    return r[0] if r and r[0] is not None else 0


def family():
    """[(id, title, last message ts)] of every "Hermes's Terminal" / "... #N" conversation, newest first."""
    if not (HH / "state.db").exists():
        return []
    t = cfg()["title"]
    c = db()
    like = t.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + " #%"
    rows = c.execute("SELECT id, title FROM sessions WHERE (title = ? OR title LIKE ? ESCAPE '\\') "
                     "AND COALESCE(archived,0)=0", (t, like)).fetchall()
    return sorted(((sid, title, last_ts(c, sid)) for sid, title in rows), key=lambda x: x[2], reverse=True)


def newest_cli(after=0):
    """Newest normal terminal conversation (not a queued request, not the desktop app), optionally started after `after`."""
    if not (HH / "state.db").exists():
        return None
    c = db()
    row = c.execute(
        "SELECT s.id FROM sessions s JOIN messages m ON m.session_id = s.id "
        "WHERE s.source IN ('local','cli') AND COALESCE(s.created_source,'cli') != 'desktop' "
        "AND COALESCE(s.archived,0)=0 AND s.started_at >= ? "
        "AND NOT EXISTS (SELECT 1 FROM messages f WHERE f.session_id = s.id AND f.role='user' AND f.content LIKE ?) "
        "GROUP BY s.id ORDER BY MAX(m.timestamp) DESC LIMIT 1", (after, QUEUE_PREFIX + "%")).fetchone()
    return row[0] if row else None


def current():
    f = family()
    return f[0][0] if f else None


def _next_title():
    t = cfg()["title"]
    nums = [1]
    for _, title, _ in family():
        m = re.fullmatch(re.escape(t) + r" #(\d+)", title or "")
        nums.append(int(m.group(1)) if m else 1)
    return t if len(family()) == 0 else f"{t} #{max(nums) + 1}"


def pin_only(sid):
    """Pin `sid`, unpin the older conversations of the family (one favourite in the app)."""
    c = db()
    pinned = lambda s: bool((c.execute("SELECT COALESCE(pinned,0) FROM sessions WHERE id=?", (s,)).fetchone() or [0])[0])
    for other, _, _ in family():
        if other != sid and pinned(other):
            hermes("sessions", "unpin", other)
    if not pinned(sid):  # each call starts Hermes once: only when something changes
        hermes("sessions", "pin", sid)


def adopt(sid, summary_file=None):
    titles = {s: t for s, t, _ in family()}
    if sid not in titles:
        rc, out = hermes("sessions", "rename", sid, _next_title())
        if rc:
            print("hermes-terminal: could not name the conversation: " + out.strip()[-300:])
            return 1
    pin_only(sid)
    if summary_file:
        text = Path(summary_file).read_text(encoding="utf-8").strip()
        if text:
            st = state()
            st["summaries"][sid] = {"ts": time.time(), "text": text}
            wj(STATE, st)
    return 0


def open_():
    sid = current()
    if not sid:
        old = newest_cli()
        if old:  # first time: the conversation you were in becomes the terminal conversation
            adopt(old)
            sid = current()
    if sid:
        if summary_stale(sid):
            summarize(sid)  # e.g. the terminal was closed with the X last time
        prepare(sid)
        pin_only(sid)
        print(sid)
    else:
        prepare("")


def close(started=None):
    started = float(started or 0)
    sid = current()
    new = newest_cli(after=started - 5) if started else None
    if new and new != sid and (not sid or last_ts(db(), new) > last_ts(db(), sid)):
        adopt(new)  # no terminal conversation yet (first run) or one was started now
        sid = new
    if sid:
        summarize(sid)


# ---------------------------------------------------------------- recap ---
NOISE = re.compile(r"^\s*(\[ran tool: [^\]]*\]|\[Image attached at: .*\]|\[screenshot\])\s*$")
SYSTEM_MSG = ("[IMPORTANT: Background process", "[INTERNAL NOTIFICATION")
HEADERS = ("[Context from the interrupted assistant response]", "[This response was interrupted by a user correction.]")


def clean(t):
    t = (t or "").strip()
    if t.startswith(SYSTEM_MSG):
        return ""
    lines = [l for l in t.splitlines() if not NOISE.match(l) and l.strip() not in HEADERS]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


def summary_stale(sid):
    s = cfg()["summary"]
    if not s.get("enabled") or not s.get("provider"):
        return False
    return state()["summaries"].get(sid, {}).get("ts", 0) < last_ts(db(), sid)


def _hermes_imports():
    import glob
    agent_dir = str(HH / "hermes-agent")
    if agent_dir not in sys.path:
        sys.path.insert(0, agent_dir)
    for f in glob.glob(str(HH / "installs" / "*" / "facts.json")):
        try:
            env = json.load(open(f, encoding="utf-8"))["packages"]["venv"]["environment"]
        except Exception:
            continue
        for sp in (os.path.join(env, "Lib", "site-packages"), *glob.glob(os.path.join(env, "lib", "python3*", "site-packages"))):
            if os.path.isdir(sp) and sp not in sys.path:
                sys.path.insert(1, sp)
    os.environ.setdefault("HERMES_HOME", str(HH))


def summarize(sid=None):
    """3-line recap of the terminal conversation. Offline it fails silently and is retried on the next open."""
    s = cfg()["summary"]
    sid = sid or current()
    if not sid or not s.get("enabled") or not s.get("provider"):
        return
    c = db()
    ts = last_ts(c, sid)
    st = state()
    if st["summaries"].get(sid, {}).get("ts", 0) >= ts:
        return
    rows = c.execute("SELECT role, content, tool_calls FROM messages WHERE session_id=? AND role IN ('user','assistant') "
                     "ORDER BY timestamp, id", (sid,)).fetchall()
    msgs = [(r, clean(t)) for r, t, tc in rows if (t or "").strip() and not (r == "assistant" and tc)]
    msgs = [m for m in msgs if m[1]][-14:]
    if not msgs:
        return
    conv = "\n\n".join(("USER: " if r == "user" else "HERMES: ") + t[:1500] for r, t in msgs)
    prompt = (f"Summarize in {s.get('language') or 'English'}, in at most 3 short lines (about 90 characters each), "
              "what this conversation between the user and the Hermes assistant is about and where it stopped, "
              "so the user remembers when resuming. No markdown, no introduction, one idea per line.")
    _hermes_imports()
    import io, contextlib, logging
    logging.disable(logging.WARNING)
    try:
        from agent.auxiliary_client import call_llm
        with contextlib.redirect_stderr(io.StringIO()):
            r = call_llm(provider=s["provider"], model=s.get("model") or None,
                         messages=[{"role": "system", "content": prompt}, {"role": "user", "content": conv}],
                         max_tokens=1000, temperature=None, timeout=60, reasoning_config={"enabled": False})
        text = (r.choices[0].message.content or "").strip()
    except Exception:
        text = ""
    if text:
        st = state()
        st["summaries"][sid] = {"ts": ts, "text": "\n".join([l.strip(" -*\t") for l in text.splitlines() if l.strip()][:3])}
        wj(STATE, st)


def prepare(sid=""):
    """Puts the recap above the resumed conversation (Hermes locale overlay cli.resume.earlier_messages).
    Never touches an en.yaml overlay that this skill (or older hermes-device-sync) did not create."""
    path = HH / "locales" / "en.yaml"
    if path.exists():
        head = path.read_text(encoding="utf-8")
        if not head.startswith((MARK, LEGACY_MARK)):
            return
    summ = state()["summaries"].get(sid, {}).get("text", "") if sid else ""
    if not summ:
        if path.exists():
            path.unlink()
        return
    body = "Recap:\n" + "\n".join("    " + l.replace("{", "{{").replace("}", "}}") for l in summ.splitlines())
    body += "\n\n  ... {count} earlier messages ..."
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(MARK + "\ncli:\n  resume:\n    earlier_messages: " + json.dumps(body, ensure_ascii=False) + "\n",
                    encoding="utf-8")


if __name__ == "__main__":
    a = sys.argv[1:]
    cmd = a[0] if a else ""
    if cmd == "open":
        open_()
    elif cmd == "close":
        close(a[1] if len(a) > 1 else None)
    elif cmd == "adopt" and len(a) >= 2:
        sys.exit(adopt(a[1], a[2] if len(a) > 2 else None))
    elif cmd == "summarize":
        summarize(a[1] if len(a) > 1 else None)
    elif cmd == "current":
        print(current() or "")
    elif cmd == "recap":
        print(state()["summaries"].get(a[1] if len(a) > 1 else (current() or ""), {}).get("text", ""))
    else:
        print(__doc__)
